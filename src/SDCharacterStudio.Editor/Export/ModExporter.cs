using System.IO;
using System.Text.RegularExpressions;
using Mono.Cecil;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace SDCharacterStudio.Editor.Export;

/// <summary>What players install to see the scenes (Q-17).</summary>
public enum ExportTarget
{
    /// <summary>One complete SMAPI mod: the scenes with the engine inside. Players need nothing else.</summary>
    CompleteMod,
    /// <summary>The scenes as a folder to put in a C# mod that embeds the engine with <c>Sdcs.cs</c>.</summary>
    CodeModScenes,
    /// <summary>A content pack for the SDCharacterStudio framework mod (players install the framework too).</summary>
    ContentPack,
}

/// <summary>
/// Writes a saved pack as a complete mod or as a scenes folder for a C# mod. A complete mod is the pack's files, a mod
/// manifest, and the embedding entry DLL renamed after the mod, so no two exported mods share an assembly name.
/// </summary>
public static class ModExporter
{
    public const string StubFileName = "SDCharacterStudio.EmbedStub.dll";

    /// <summary>The entry DLL shipped with the editor (built from SDCharacterStudio.EmbedStub).</summary>
    public static string StubPath => Path.Combine(AppContext.BaseDirectory, "Embed", StubFileName);

    /// <summary>The drop-in engine for C# mods (generated by the SDCharacterStudio.Engine build).</summary>
    public static string DropInPath => Path.Combine(AppContext.BaseDirectory, "Embed", "Sdcs.cs");

    public const string ScenesFolder = "scenes";

    /// <summary>"Player.Raincoat" → "Player.Raincoat": the mod's assembly and DLL name.</summary>
    public static string AssemblyName(string uniqueId)
    {
        string name = Regex.Replace(uniqueId, "[^A-Za-z0-9._]", "_").Trim('.', '_');
        return name.Length == 0 ? "SdcsScenes" : char.IsLetter(name[0]) ? name : "Sdcs_" + name;
    }

    /// <summary>A default output folder next to the project: Export/&lt;name&gt;.</summary>
    public static string DefaultFolder(PackDocument document, ExportTarget target) =>
        Path.Combine(Path.GetDirectoryName(document.ProjectPath)!, "Export", PackDocument.SafeFileName(document.DisplayName) + (target == ExportTarget.CodeModScenes ? " for my mod" : ""));

    /// <summary>Write the complete mod into <paramref name="folder"/> (replacing an earlier export of the same mod).</summary>
    public static void WriteCompleteMod(PackDocument document, string folder, string? stubPath = null)
    {
        stubPath ??= StubPath;
        if (!File.Exists(stubPath)) throw new FileNotFoundException($"The editor's embedding DLL is missing ({stubPath}). Rebuild the editor.", stubPath);
        PrepareFolder(folder, document.PackId);
        CopyPackFiles(document.PackFolder, folder);
        string assemblyName = AssemblyName(document.PackId);
        var manifest = JObject.Parse(PackWriter.Serialize(document.Manifest));
        manifest.Remove("ContentPackFor");
        manifest["EntryDll"] = assemblyName + ".dll";
        manifest["MinimumApiVersion"] = "4.0.0";
        if (manifest["Dependencies"] is JArray { Count: 0 }) manifest.Remove("Dependencies");
        File.WriteAllText(Path.Combine(folder, "manifest.json"), manifest.ToString(Formatting.Indented).Replace("\r\n", "\n") + "\n");
        using var stub = AssemblyDefinition.ReadAssembly(stubPath);
        stub.Name.Name = assemblyName;
        stub.MainModule.Name = assemblyName + ".dll";
        stub.Write(Path.Combine(folder, assemblyName + ".dll"));
    }

    /// <summary>
    /// Everything a C# mod needs: <c>Sdcs.cs</c> (the engine in one file) and the <c>scenes</c> folder (the pack's files
    /// without its manifest; the mod has its own), with a short read-me.
    /// </summary>
    public static void WriteScenes(PackDocument document, string folder, string? dropInPath = null)
    {
        dropInPath ??= DropInPath;
        if (!File.Exists(dropInPath)) throw new FileNotFoundException($"The editor's Sdcs.cs is missing ({dropInPath}). Rebuild the editor.", dropInPath);
        PrepareFolder(folder, null);
        CopyPackFiles(document.PackFolder, Path.Combine(folder, ScenesFolder));
        File.Copy(dropInPath, Path.Combine(folder, "Sdcs.cs"), true);
        File.WriteAllText(Path.Combine(folder, "README.txt"),
            $"Scenes from \"{document.DisplayName}\", made with SDCharacterStudio, for your C# SMAPI mod.\n\n" +
            "1. Copy Sdcs.cs into your mod's project (it compiles like any other file).\n" +
            "2. Copy the scenes folder into your mod, with its files set to copy to the build output:\n" +
            "     <None Update=\"scenes\\**\\*\" CopyToOutputDirectory=\"PreserveNewest\" />\n" +
            "3. In your ModEntry.Entry:  Sdcs.Register(this);\n\n" +
            "Scenes play by themselves when their conditions are met. To play one from your code: Sdcs.Play(\"scene-id\").\n" +
            "Players install only your mod.\n");
    }

    private static void CopyPackFiles(string source, string target)
    {
        PackExporter.CopyDirectory(source, target);
        string copiedManifest = Path.Combine(target, "manifest.json");
        if (File.Exists(copiedManifest)) File.Delete(copiedManifest);
    }

    /// <summary>An empty folder, or one that already holds this export: never overwrite somebody else's mod.</summary>
    private static void PrepareFolder(string folder, string? modId)
    {
        if (Directory.Exists(folder) && Directory.EnumerateFileSystemEntries(folder).Any())
        {
            string manifest = Path.Combine(folder, "manifest.json");
            bool ours = modId == null ? File.Exists(Path.Combine(folder, ScenesFolder, "studio.json")) && File.Exists(Path.Combine(folder, "Sdcs.cs")) && !File.Exists(manifest)
                : File.Exists(manifest) && File.ReadAllText(manifest).Contains("\"" + modId + "\"", StringComparison.OrdinalIgnoreCase) && File.Exists(Path.Combine(folder, "studio.json"));
            if (!ours) throw new IOException($"{folder} already holds something else. Choose an empty folder or an earlier export of this pack.");
            Directory.Delete(folder, recursive: true);
        }
        Directory.CreateDirectory(folder);
    }
}
